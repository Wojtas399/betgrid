#!/usr/bin/env python3
"""Pulls the gitignored Firebase config files for each flavor from Firebase.

usage: python3 tool/firebase_config.py [dev|prod ...]   (default: dev prod)
Needs the Firebase CLI logged in to an account with access to both projects.
"""
import json
import plistlib
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PROJECTS = {'dev': 'betgrid-dev', 'prod': 'betgrid-9c57d'}
BUNDLE_SUFFIX = {'dev': '.dev', 'prod': ''}
APPS = {
    'client': {'IOS': 'com.example.betgrid', 'ANDROID': 'com.example.betgrid'},
    'admin': {'IOS': 'com.example.betgridAdmin'},
}


def firebase(*args):
    out = subprocess.run(['firebase', *args, '--json'], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f'firebase {" ".join(args)} failed:\n{out.stdout}{out.stderr}')
    return json.loads(out.stdout)['result']


def sdk_config(project, platform, bundle_id, apps):
    app = next((a for a in apps if a['platform'] == platform and a['namespace'] == bundle_id), None)
    if app is None:
        sys.exit(f'No {platform} app {bundle_id} in Firebase project {project}')
    return firebase('apps:sdkconfig', platform, app['appId'], '--project', project)['fileContents']


def ios_options(plist):
    return {
        'apiKey': plist['API_KEY'],
        'appId': plist['GOOGLE_APP_ID'],
        'messagingSenderId': plist['GCM_SENDER_ID'],
        'projectId': plist['PROJECT_ID'],
        'storageBucket': plist['STORAGE_BUCKET'],
        'iosClientId': plist['CLIENT_ID'],
        'iosBundleId': plist['BUNDLE_ID'],
    }


def android_options(services, package):
    client = next(c for c in services['client'] if c['client_info']['android_client_info']['package_name'] == package)
    return {
        'apiKey': client['api_key'][0]['current_key'],
        'appId': client['client_info']['mobilesdk_app_id'],
        'messagingSenderId': services['project_info']['project_number'],
        'projectId': services['project_info']['project_id'],
        'storageBucket': services['project_info']['storage_bucket'],
    }


def dart_options(env, options):
    platforms = {'IOS': ('iOS', 'ios'), 'ANDROID': ('android', 'android')}
    cases = ''.join(f'    TargetPlatform.{platforms[p][0]} => {platforms[p][1]},\n' for p in options)
    fields = ''
    for platform, values in options.items():
        body = ''.join(f"    {key}: '{value}',\n" for key, value in values.items())
        fields += f'\n  static const FirebaseOptions {platforms[platform][1]} = FirebaseOptions(\n{body}  );\n'
    return f"""// Generated by tool/firebase_config.py for the {env} flavor. Do not edit.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart' show defaultTargetPlatform, TargetPlatform;

class DefaultFirebaseOptions {{
  static FirebaseOptions get currentPlatform => switch (defaultTargetPlatform) {{
{cases}    _ => throw UnsupportedError('No {env} Firebase options for $defaultTargetPlatform'),
  }};
{fields}}}
"""


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print('wrote', path.relative_to(REPO))


def pull(env):
    project = PROJECTS[env]
    apps = firebase('apps:list', '--project', project)
    for app, bundles in APPS.items():
        app_dir = REPO / app
        options = {}
        for platform, base_id in bundles.items():
            bundle_id = base_id + BUNDLE_SUFFIX[env]
            contents = sdk_config(project, platform, bundle_id, apps)
            if platform == 'IOS':
                plist = plistlib.loads(contents.encode())
                options[platform] = ios_options(plist)
                client_id = plist['CLIENT_ID'].removesuffix('.apps.googleusercontent.com')
                write(
                    app_dir / f'ios/Runner/Keys-{env}.xcconfig',
                    f'FIREBASE_CLIENT_ID = {client_id}\nFIREBASE_IOS_APP_ID = {plist["GOOGLE_APP_ID"]}\n',
                )
            else:
                options[platform] = android_options(json.loads(contents), bundle_id)
                write(app_dir / f'android/app/src/{env}/google-services.json', contents)
        write(app_dir / f'lib/firebase_options_{env}.dart', dart_options(env, options))


for env in sys.argv[1:] or PROJECTS:
    pull(env)
